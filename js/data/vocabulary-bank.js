export function getRandomVocab(count = 5, level = null) {
  let pool = VOCABULARY_BANK;
  if (level) {
    pool = pool.filter(v => v.cefr === level);
    if (pool.length === 0) pool = VOCABULARY_BANK;
  }
  const shuffled = [...pool].sort(() => 0.5 - Math.random());
  return shuffled.slice(0, count);
}
